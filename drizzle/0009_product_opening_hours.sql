-- 0009_product_opening_hours — 상품별 영업시간 (FR-PRD-010 확장, 9/14 결정).
--
-- 상품마다 받는 시간이 다른 매장이 있다 — 심야 클래스, 점심에만 하는 시술. 지금까지는 사업장 영업시간 하나뿐이라
-- 그런 상품을 만들 수 없었다.
--
-- 빈 배열이 **기본이자 "정하지 않음"** 이다: 그 상품은 사업장 영업시간을 그대로 따른다(옛 행의 동작이 바뀌지 않는다).
-- 값이 있으면 그 상품에 한해 사업장 영업시간 **대신** 이것을 쓴다. 형식은 businesses.opening_hours 와 같다.
--
-- NOT NULL DEFAULT '[]' 인 이유: 슬롯 계산이 이 값의 **길이로 "정했는가" 를 판정하는 술어 컬럼**이라
-- NULL 이 섞이면 그 분기가 세 갈래가 된다 (08 §5.6).
--
-- 확장 방향이라 옛 코드가 이 스키마에서 그대로 돈다(컬럼을 읽지 않을 뿐). 새 코드는 옛 스키마에서 부팅되지 않으므로
-- **마이그레이션이 배포보다 먼저**다.
ALTER TABLE "products" ADD COLUMN "opening_hours" jsonb DEFAULT '[]'::jsonb NOT NULL;
